/**
 * encyclopedia-seed —— 一次性把 7 条真实校园内容灌进 encyclopedia（契约 §3）
 *
 * 为什么 publish_date 写今天（北京时间）而不是留空串：留空串时首页拿到的
 * src 永远是 'latest'，按契约 §5 那就是一张「今日还没更新」的空卡 ——
 * 灌了数据也看不到东西。写今天当天就是 'today'，第二天自然回落成「往期」。
 *
 * 为什么 7 条要错开日期（今天、昨天……前 6 天）而不是全写今天：
 * encyclopedia.publish_date 有唯一索引（契约 §1「一天一条」），全写今天
 * 会让第 2-7 条被唯一键挡下，7 条只进 1 条。错开既满足唯一约束，
 * 又让第一条落在今天 —— 首页今天命中 'today'，其余作为往期存档。
 *
 * 用法：部署后调一次即可。按 title 查重：没有就插入，**有但正文变了就原地刷新**，
 * 完全一致才算跳过。所以改了内容只重传这个函数再跑一次就行，不需要 { reset: true }。
 * 想彻底重来：传 { reset: true }，会先清空 active: true 的旧数据再插。
 */

const DB_ENCYCLOPEDIA = 'encyclopedia';

// 服务器跑 UTC：北京时间 0-8 点直接取 UTC 日期会算成昨天，
// 灌进去的日期就跟用户眼里的「今天」对不上，得先加 8 小时再切日期。
const BJ_OFFSET_MS = 8 * 60 * 60 * 1000;
const DAY_MS = 24 * 60 * 60 * 1000;

// offsetDays=0 是今天，1 是昨天……倒着排，保证第一条就是今天这条
function bjDate(offsetDays) {
  return new Date(Date.now() + BJ_OFFSET_MS - offsetDays * DAY_MS).toISOString().slice(0, 10);
}

