exports.main = async (event) => {
  event = event || {};
  const db = uniCloud.database();
  const col = db.collection(DB_ENCYCLOPEDIA);

  if (event.reset === true) {
    // 只清 active: true 的演示数据：被人为停用的那几条是有意保留的，
    // 不该被一次重灌顺手带走
    try {
      await col.where({ active: true }).remove();
    } catch (e) {
      // 表还没建时删不掉，不是错误：下面的插入会自己建表
      console.warn('[encyclopedia-seed] 清空旧数据失败（表可能还没建）：', e && e.message);
    }
  }

  let inserted = 0;
  let updated = 0;
  let skipped = 0;
  const now = Date.now();

  for (let i = 0; i < SEED.length; i++) {
    const item = SEED[i];
    try {
      // 按 title 查重，保证可重复调用
      const exist = await col.where({ title: item.title }).limit(1).get();
      const row = exist.data && exist.data[0];
      if (row) {
        // 已存在就**原地刷新正文**，而不是一律跳过。
        // 上一版内容只有 60-80 字，够不到首页的「展开」阈值；如果这里继续跳过，
        // 重传函数也救不回来，用户还得先学会传 {reset:true} 才看得到新内容。
        // publish_date 不动：它有唯一索引，改了可能和别的日子撞。
        if (row.content !== item.content || row.category !== item.category) {
          await col.doc(row._id).update({ content: item.content, category: item.category });
          updated++;
        } else {
          skipped++;
        }
        continue;
      }

      await col.add({
        title: item.title,
        content: item.content,
        category: item.category,
        // 见文件头：第一条=今天，其余错开成往期，唯一索引才放得过 7 条
        // i=0 是昨天，往前推：**故意不含今天**，首页第一眼就是「往期」态；
        // 想看「今天」态，去百科配置页新增一条 publish_date=今天的。
        publish_date: bjDate(i + 1),
        active: true,
        // 加 i 毫秒：一次灌入的 7 条 created_at 完全相同，daily 按倒序回落时
        // 就分不出谁是最新，同一个用户两次刷新可能看到不同的一条
        created_at: now + i
      });
      inserted++;
    } catch (e) {
      // 单条失败不拖垮整批（唯一索引或字段校验会挡），算跳过并留一行日志便于排查
      skipped++;
      console.error('[encyclopedia-seed] 第 ' + (i + 1) + ' 条写入失败：' + item.title, e && e.message);
    }
  }

  return { code: 0, msg: 'ok', data: { inserted: inserted, updated: updated, skipped: skipped } };
};
